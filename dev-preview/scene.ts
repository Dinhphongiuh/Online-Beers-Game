import { initThreeScene } from '../src/game/threeScene';
import { INITIAL_PLAYERS } from '../src/App';
import { DEFAULT_HUMAN_APPEARANCE } from '../shared/appearance';
const params = new URLSearchParams(location.search);
const scene = initThreeScene();
scene.mount(document.getElementById('m') as HTMLDivElement);
scene.setLobbyMode((params.get('mode') as any) || 'wardrobe');
const me = { ...INITIAL_PLAYERS[0], seatIndex: 0, alcoholLevel: 30, appearance: { ...DEFAULT_HUMAN_APPEARANCE, gender: 'female' } };
scene.updatePlayers([me as any]);
(window as any).sc = scene;
